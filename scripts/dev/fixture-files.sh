#!/usr/bin/env bash
# scripts/dev/fixture-files.sh
#
# Writes FerroLICENCE/FerroLICENCE/Fixtures/RepositoryFiles.swift from the
# register's public files as they were when it moved to its own repository
# (FerroLicenceKit/Tests/RegisterSnapshot): the trust anchors, signers.json
# and the free licence. The app's fixture mode (previews, the screenshot
# tour) starts from them.

set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

python3 - <<'PY'
import glob, os

os.chdir("FerroLicenceKit/Tests/RegisterSnapshot")

paths = sorted(glob.glob("keys/*.asc") + glob.glob("keys/retired/*.asc")) + ["signers.json"]
paths += sorted(glob.glob("register/*/01a1175c*/*"))
out = [
    "// Generated by scripts/dev/fixture-files.sh from the repository's public files:",
    "// the trust anchors, signers.json and the free licence. Debug builds only.",
    "",
    "#if DEBUG",
    "",
    "/// The repository files the fixtures start from, by path. Each text has its",
    "/// final line break, as on disk.",
    "nonisolated let repositoryFixtureFiles: [String: String] = [",
]
for p in paths:
    text = open(p).read()
    assert "PRIVATE KEY" not in text, p
    body = text[:-1] if text.endswith("\n") else text
    out.append(f'    "{p}": #"""\n{body}\n\n"""#,')
out += ["]", "", "#endif"]
open("../../../FerroLICENCE/FerroLICENCE/Fixtures/RepositoryFiles.swift", "w").write("\n".join(out) + "\n")
PY
